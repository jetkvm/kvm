// extendedScancodeMap handles E0-prefixed scancodes.
// Key is the scancode byte (without E0 prefix), value is HID code.
var extendedScancodeMap = map[uint8]uint8{
	// Navigation cluster
	0x47: 0x4A, // Home
	0x48: 0x52, // Up Arrow
	0x49: 0x4B, // Page Up
	0x4B: 0x50, // Left Arrow
	0x4D: 0x4F, // Right Arrow
	0x4F: 0x4D, // End
	0x50: 0x51, // Down Arrow
	0x51: 0x4E, // Page Down
	0x52: 0x49, // Insert
	0x53: 0x4C, // Delete

	// Modifier keys
	0x1C: 0x58, // Numpad Enter
	0x1D: 0xE4, // Right Control
	0x35: 0x54, // Numpad /
	0x38: 0xE6, // Right Alt (AltGr)

	// Windows/GUI keys
	0x5B: 0xE3, // Left GUI (Windows/Command)
	0x5C: 0xE7, // Right GUI (Windows/Command)
	0x5D: 0x65, // Application/Menu

	// System keys
	0x37: 0x46, // Print Screen
	0x45: 0x48, // Pause/Break (Note: requires special handling)
	0x46: 0x48, // Ctrl+Pause = Break

	// Power management (Mac and some PC keyboards)
	0x5E: 0x66, // Power
	0x5F: 0x82, // Sleep (System Sleep)
	0x63: 0x83, // Wake (System Wake Up)

	// Multimedia keys (mapped to Consumer HID page where possible)
	// These require USB Consumer Control page, but we map to keyboard equivalents
	0x10: 0x00, // Previous Track (Consumer)
	0x19: 0x00, // Next Track (Consumer)
	0x20: 0x7F, // Mute -> HID Mute
	0x21: 0x00, // Calculator launch
	0x22: 0x00, // Play/Pause (Consumer)
	0x24: 0x00, // Stop (Consumer)
	0x2E: 0x81, // Volume Down -> HID Volume Down
	0x30: 0x80, // Volume Up -> HID Volume Up

	// Browser keys (no HID keyboard equivalents)
	0x6A: 0x00, // Browser Back
	0x69: 0x00, // Browser Forward
	0x6C: 0x00, // Browser Home
	0x65: 0x00, // Browser Search
	0x66: 0x00, // Browser Favorites
	0x32: 0x00, // Browser Refresh
	0x6B: 0x00, // Browser Stop

	// App launch keys (no standard HID keyboard equivalents)
	0x6D: 0x00, // Media Player
	0x6E: 0x00, // Email
	0x6F: 0x00, // My Computer

	// Korean keyboard keys
	0xF1: 0x90, // Hangul (Korean/English toggle)
	0xF2: 0x91, // Hanja (Chinese character input)

	// Japanese keyboard extended keys
	0x64: 0x87, // International1 (Ro key, sometimes extended)
	0x70: 0x88, // International2 (Katakana/Hiragana)
}
