package rdp

// RDP scancode to USB HID code conversion (MS-RDPBCGR 2.2.8.1.1.3.1.1.1).
//
// Supports all common keyboard layouts:
//   - US ANSI (104-key)
//   - UK/British ISO (105-key)
//   - German QWERTZ
//   - French AZERTY
//   - Nordic layouts
//   - Japanese JIS (106/109-key)
//   - Korean (103/106-key)
//   - Mac extended keyboards (F13-F24)
//
// References:
//   - MS-RDPBCGR: https://learn.microsoft.com/en-us/openspecs/windows_protocols/ms-rdpbcgr
//   - USB HID Usage Tables 1.5: https://usb.org/document-library/hid-usage-tables-15
//   - Scancode Set 1: https://wiki.osdev.org/Keyboard#Scan_Code_Set_1

// scancodeToHID converts an RDP Set 1 scancode to USB HID usage code.
// Returns 0 for unsupported scancodes.
func scancodeToHID(scancode uint16, flags uint16) uint8 {
	extended := flags&0x0100 != 0

	// Extended scancodes (E0 prefix in Set 1)
	if extended {
		return extendedScancodeToHID(scancode)
	}

	// Base scancodes
	return baseScancodeToHID(scancode)
}

// baseScancodeToHID handles non-extended scancodes.
func baseScancodeToHID(scancode uint16) uint8 {
	if scancode < uint16(len(baseScancodeTable)) {
		return baseScancodeTable[scancode]
	}
	return 0
}

// extendedScancodeToHID handles extended (E0-prefixed) scancodes.
func extendedScancodeToHID(scancode uint16) uint8 {
	if hid, ok := extendedScancodeMap[uint8(scancode)]; ok {
		return hid
	}
	return 0
}

